"""Offline guardrail: legacy Amazon campaign attribution must normalize untrusted labels.

No HTTP calls, DB writes, clicks or conversions are generated by these tests.
"""
import ast
from pathlib import Path
import unittest
from p0_tag_acquisition import classify_channel, safe_campaign, tag_for_channel


class CampaignAttributionTests(unittest.TestCase):
    def test_unknown_source_does_not_claim_social_referrer(self):
        self.assertEqual(classify_channel("unverified-facebook"), "direct")
        self.assertEqual(classify_channel(" FACEBOOK "), "facebook")

    def test_generic_social_label_fails_closed(self):
        # The legacy vitrine emits channel=social, which is NOT a verified
        # Instagram/Facebook/TikTok referrer and must never imply TAG_02.
        self.assertEqual(classify_channel("social"), "direct")
        self.assertEqual(tag_for_channel("social"), "DIRECT")
        self.assertEqual(tag_for_channel("unverified-facebook"), "DIRECT")

    def test_invalid_campaign_labels_are_not_persisted(self):
        self.assertEqual(safe_campaign("https://example.test/?token=secret"), "")
        self.assertEqual(safe_campaign("werozinha-amazon"), "werozinha-amazon")

    def test_legacy_get_is_read_only_and_requires_explicit_outbound_post(self):
        source = (Path(__file__).resolve().parents[1] / "main.py").read_text(encoding="utf-8")
        tree = ast.parse(source)
        legacy = next(n for n in tree.body if isinstance(n, ast.FunctionDef)
                      and n.name == "werozinha_one_click_amazon")
        route_source = ast.get_source_segment(source, legacy)
        # A GET may come from previews/crawlers; only POST /out counts outbound clicks.
        self.assertNotIn("INSERT INTO clicks", route_source)
        self.assertNotIn("conn.commit()", route_source)
        self.assertIn('landing = f"/go/{offer_id}', route_source)
        self.assertIn("return RedirectResponse(landing, status_code=302)", route_source)
        outbound = next(n for n in tree.body if isinstance(n, ast.FunctionDef)
                        and n.name == "confirm_offer_click")
        decorators = [ast.get_source_segment(source, d) for d in outbound.decorator_list]
        self.assertTrue(any('app.post("/out/{offer_id}")' in d for d in decorators))

    def test_legacy_get_route_normalizes_before_database_access(self):
        source = (Path(__file__).resolve().parents[1] / "main.py").read_text(encoding="utf-8")
        tree = ast.parse(source)
        route = next(n for n in tree.body if isinstance(n, ast.FunctionDef)
                     and n.name == "werozinha_one_click_amazon")
        call_positions = {}
        for n in ast.walk(route):
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Name):
                call_positions.setdefault(n.func.id, []).append(n.lineno)
        self.assertIn("classify_channel", call_positions)
        self.assertIn("safe_campaign", call_positions)
        self.assertIn("db", call_positions)
        self.assertLess(min(call_positions["classify_channel"]), min(call_positions["db"]))
        self.assertLess(min(call_positions["safe_campaign"]), min(call_positions["db"]))


if __name__ == "__main__":
    unittest.main()
